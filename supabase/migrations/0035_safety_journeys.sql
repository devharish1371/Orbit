-- Explicit check-ins do not collect location. Private timers are the default.
create table public.safety_journeys (
 id uuid primary key, couple_id uuid not null references public.couples(id) on delete cascade,
 user_id uuid not null references public.members(user_id) on delete cascade,
 destination text not null check(length(btrim(destination)) between 1 and 100),
 deadline timestamptz not null, state text not null default 'active' check(state in ('active','checked_in','cancelled')),
 share_overdue boolean not null default false, version int not null default 1 check(version>0),
 last_request uuid not null, queued_version int,
 created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create unique index safety_one_active on public.safety_journeys(user_id) where state='active';
create index safety_due on public.safety_journeys(deadline) where state='active';
alter table public.safety_journeys enable row level security;
create policy safety_read on public.safety_journeys for select to authenticated using(
 couple_id=orbit_private.my_couple_id() and (user_id=auth.uid() or (share_overdue and exists(
 select 1 from public.members m where m.user_id=safety_journeys.user_id and m.share_mode='live'))));
revoke all on public.safety_journeys from public,anon,authenticated;
grant select on public.safety_journeys to authenticated;
grant all on public.safety_journeys to service_role;

create function public.save_safety_journey(p_expected_user uuid,p_expected_couple uuid,p_id uuid,p_version int,p_request uuid,p_action text,p_destination text default null,p_deadline timestamptz default null,p_share boolean default false)
returns public.safety_journeys language plpgsql security definer set search_path='' as $$
declare c uuid; item public.safety_journeys;
begin
 c:=orbit_private.my_couple_id();
 if c is null or p_expected_user is distinct from auth.uid() or p_expected_couple is distinct from c then raise exception 'ACCOUNT_CHANGED'; end if;
 perform 1 from public.couples where id=c for update;
 if p_id is null or p_request is null or p_action is null or p_action not in ('start','check_in','cancel','extend') then raise exception 'INVALID_JOURNEY'; end if;
 select * into item from public.safety_journeys where id=p_id for update;
 if found then
  if item.user_id<>auth.uid() or item.couple_id<>c then raise exception 'JOURNEY_UNAVAILABLE'; end if;
  -- Exact request replay is accepted only for the same operation/result payload.
  if item.last_request=p_request and (
   (p_action='start' and p_version is null and item.version=1 and item.destination=btrim(p_destination) and item.deadline=p_deadline and item.share_overdue=p_share) or
   (item.version=p_version+1 and ((p_action='check_in' and item.state='checked_in') or (p_action='cancel' and item.state='cancelled') or (p_action='extend' and item.state='active' and item.deadline=p_deadline)))
  ) then return item; end if;
  if p_version is null or item.version<>p_version then raise exception 'JOURNEY_CHANGED'; end if;
  if item.state<>'active' then raise exception 'JOURNEY_CLOSED'; end if;
  if p_action='start' then raise exception 'JOURNEY_CHANGED'; end if;
  if p_action='extend' and (p_deadline is null or not isfinite(p_deadline) or p_deadline<=greatest(now(),item.deadline) or p_deadline>now()+interval '24 hours') then raise exception 'INVALID_DEADLINE'; end if;
  update public.safety_journeys set state=case p_action when 'check_in' then 'checked_in' when 'cancel' then 'cancelled' else 'active' end,
   deadline=case when p_action='extend' then p_deadline else deadline end, version=version+1,last_request=p_request,queued_version=null,updated_at=now() where id=p_id returning * into item;
 else
  if p_action<>'start' or p_version is not null then raise exception 'JOURNEY_UNAVAILABLE'; end if;
  if p_destination is null or length(btrim(p_destination)) not between 1 and 100 or p_share is null
   or p_deadline is null or not isfinite(p_deadline) or p_deadline<now()+interval '2 minutes' or p_deadline>now()+interval '24 hours' then raise exception 'INVALID_JOURNEY'; end if;
  -- Abandoned timers have a bounded lifetime; no stale alert can be generated by replacement.
  update public.safety_journeys set state='cancelled',version=version+1,updated_at=now() where user_id=auth.uid() and state='active' and deadline<now()-interval '1 hour';
  if exists(select 1 from public.safety_journeys where user_id=auth.uid() and state='active') then raise exception 'JOURNEY_ACTIVE'; end if;
  if (select count(*) from public.safety_journeys where user_id=auth.uid() and created_at>now()-interval '1 day')>=24 then raise exception 'JOURNEY_LIMIT'; end if;
  insert into public.safety_journeys(id,couple_id,user_id,destination,deadline,share_overdue,last_request)
   values(p_id,c,auth.uid(),btrim(p_destination),p_deadline,p_share,p_request) returning * into item;
 end if;
 return item;
end $$;
create function orbit_private.enqueue_safety_journeys_for(p_couple uuid) returns int language plpgsql security definer set search_path='' as $$
declare c record; item public.safety_journeys; n int:=0;
begin
 for c in select id from public.couples where (p_couple is null or id=p_couple) and exists(select 1 from public.safety_journeys j where j.couple_id=couples.id and j.state='active' and j.share_overdue and j.deadline<=now() and j.deadline>now()-interval '1 hour' and j.queued_version is distinct from j.version) order by id limit 100 for update skip locked loop
  for item in select j.* from public.safety_journeys j join public.members m on m.user_id=j.user_id
   where j.couple_id=c.id and j.state='active' and j.share_overdue and m.share_mode='live'
   and j.deadline<=now() and j.deadline>now()-interval '1 hour' and j.queued_version is distinct from j.version
   and exists(select 1 from public.members p where p.couple_id=c.id and p.user_id<>j.user_id and p.notify_prefs->>'safety'='true')
   for update of j skip locked loop
   insert into orbit_private.notification_jobs(source_table,record) values('safety_journeys',jsonb_build_object('journey_id',item.id,'couple_id',item.couple_id,'user_id',item.user_id,'version',item.version,'expires_at',item.deadline+interval '1 hour'));
   update public.safety_journeys set queued_version=version where id=item.id;
   n:=n+1;
  end loop;
 end loop;
 return n;
end $$;
create function orbit_private.enqueue_safety_journeys() returns int language sql security definer set search_path='' as $$select orbit_private.enqueue_safety_journeys_for(null)$$;
create function public.safety_journey_delivery(p_expected_user uuid,p_expected_couple uuid,p_id uuid) returns jsonb language plpgsql security definer set search_path='' as $$
declare item public.safety_journeys; status text;
begin
 if auth.uid() is distinct from p_expected_user or orbit_private.my_couple_id() is distinct from p_expected_couple then raise exception 'ACCOUNT_CHANGED'; end if;
 select * into item from public.safety_journeys where id=p_id and user_id=auth.uid() and couple_id=p_expected_couple;
 if not found then raise exception 'JOURNEY_UNAVAILABLE'; end if;
 select j.status into status from orbit_private.notification_jobs j where j.source_table='safety_journeys' and j.record->>'journey_id'=p_id::text and (j.record->>'version')::int=item.version order by j.created_at desc limit 1;
 return jsonb_build_object('status',coalesce(status,case when item.state<>'active' then 'closed' when not item.share_overdue then 'private' when item.deadline>now() then 'not_due' when item.deadline<now()-interval '1 hour' then 'expired' else 'not_queued' end));
end $$;
create trigger trg_social_safety after insert or update or delete on public.safety_journeys for each row execute function orbit_private.bump_social_revision();
select cron.schedule('orbit-safety-checkins','* * * * *','select orbit_private.enqueue_safety_journeys()');
create function orbit_private.cleanup_safety_journeys() returns void language plpgsql security definer set search_path='' as $$
declare c record;
begin
 for c in select id from public.couples where exists(select 1 from public.safety_journeys j where j.couple_id=couples.id and j.deadline<now()-interval '7 days') order by id limit 100 for update skip locked loop
  delete from public.safety_journeys where couple_id=c.id and deadline<now()-interval '7 days';
 end loop;
end $$;
revoke all on function orbit_private.cleanup_safety_journeys() from public,anon,authenticated;
select cron.schedule('orbit-safety-cleanup','15 * * * *','select orbit_private.cleanup_safety_journeys()');
revoke all on function public.save_safety_journey(uuid,uuid,uuid,int,uuid,text,text,timestamptz,boolean),public.safety_journey_delivery(uuid,uuid,uuid) from public,anon;
grant execute on function public.save_safety_journey(uuid,uuid,uuid,int,uuid,text,text,timestamptz,boolean),public.safety_journey_delivery(uuid,uuid,uuid) to authenticated;
revoke all on function orbit_private.enqueue_safety_journeys(),orbit_private.enqueue_safety_journeys_for(uuid) from public,anon,authenticated;
